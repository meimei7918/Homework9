<?php
// 【說明】遞增運算子與字串串接。實際輸出：2<br />2<br />1<br />12522<br />mn<br />
$i=1;
// 【說明】++$i：先加 1 再取值，所以 $i 和 $j 都是 2。
$j=++$i;

$i=1;
// 【說明】$i++：先取值再加 1，所以 $z 是 1，$i 變成 2。
$z=$i++;
echo $i."<br />";
echo $j."<br />";
echo $z."<br />"; 
// 【說明】** 是次方，5**3 = 125。後面沒有換行。
echo 5**3;
$m="m";
$n="n";

// 【說明】.= 的優先順序比 . 低，所以這行是 $i .= ($j . "<br />")，$i 變成 "22<br />"。
//   它緊接在上一行的 125 後面輸出，畫面上就變成 12522，看起來像一個數字，其實是 125 和 22。
echo $i.=$j."<br />";
echo $m.=$n."<br />";
?>